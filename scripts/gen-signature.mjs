// Generates lib/signature.js from the pinned micromark-extension-gfm / mdast-util-gfm (dev dependencies).
// `node scripts/gen-signature.mjs --check` fails when the committed file is stale.
import fs from 'node:fs'
import {gfm} from 'micromark-extension-gfm'
import {gfmFromMarkdown} from 'mdast-util-gfm'
import {frontmatter} from 'micromark-extension-frontmatter'
import {frontmatterFromMarkdown} from 'mdast-util-frontmatter'
import {math} from 'micromark-extension-math'
import {mathFromMarkdown} from 'mdast-util-math'
import {micromarkRows, mdastRows, flat} from '../lib/rows.js'
import {frontmatterProfile, mathTextProfile} from '../lib/probe.js'

const v = n => JSON.parse(fs.readFileSync(new URL(`../node_modules/${n}/package.json`, import.meta.url), 'utf8')).version
const frontmatterConfigs = {}
for (const [name, opts] of [['yaml', ['yaml']], ['toml', ['toml']], ['yaml,toml', ['yaml', 'toml']]]) {
  frontmatterConfigs[name] = {options: opts, micromark: micromarkRows(frontmatter(opts)), mdast: mdastRows(frontmatterFromMarkdown(opts)), profile: frontmatterProfile(frontmatter(opts), flat)}
}
const mathConfig = {
  micromark: micromarkRows(math()), mdast: mdastRows(mathFromMarkdown()),
  profiles: {single: mathTextProfile(math(), flat), noSingle: mathTextProfile(math({singleDollarTextMath: false}), flat)}
}
const out = `// GENERATED by scripts/gen-signature.mjs. Do not edit.
// Construct and handler names of stock GFM, verified for these versions:
//   micromark-extension-gfm ${v('micromark-extension-gfm')}, mdast-util-gfm ${v('mdast-util-gfm')}, mdast-util-from-markdown ${v('mdast-util-from-markdown')}, micromark ${v('micromark')}
//   micromark-extension-frontmatter ${v('micromark-extension-frontmatter')}, mdast-util-frontmatter ${v('mdast-util-frontmatter')}, micromark-extension-math ${v('micromark-extension-math')}, mdast-util-math ${v('mdast-util-math')}
export const micromarkSignature = ${JSON.stringify(micromarkRows(gfm()))}
export const mdastSignature = ${JSON.stringify(mdastRows(gfmFromMarkdown()))}
// optional extensions the fast parser implements natively: rows plus a behaviour profile read from the real tokenizers
export const frontmatterConfigs = ${JSON.stringify(frontmatterConfigs, null, 1)}
export const mathConfig = ${JSON.stringify(mathConfig, null, 1)}
`
const file = new URL('../lib/signature.js', import.meta.url)
if (process.argv.includes('--check')) {
  if (fs.readFileSync(file, 'utf8') !== out) { console.error('lib/signature.js is stale; run node scripts/gen-signature.mjs'); process.exit(1) }
  console.log('lib/signature.js is current')
} else { fs.writeFileSync(file, out); console.log('wrote lib/signature.js') }
